import fs from "fs";
import path from "path";
import {
  chunkRows,
  detectNumericColumns,
  isNumericCellValue,
  renderSchedulePdf,
  TABLE_ROWS_PER_PAGE,
} from "../services/reporting-analytics/analytics-schedule-pdf";
import { buildSchedulePdfKpis } from "../services/reporting-analytics/analytics-schedule-pdf-kpis";
import { getDefaultWorklenzLogoBuffer } from "../services/reporting-analytics/resolve-schedule-pdf-logo";
import type { ScheduleChartSource } from "../services/reporting-analytics/analytics-schedule-charts";

const isPdf = (buffer: Buffer): boolean => buffer.subarray(0, 5).toString() === "%PDF-";

/** Count PDF page objects — enough to assert multi-page table chunking. */
const countPdfPages = (buffer: Buffer): number => {
  const text = buffer.toString("latin1");
  const matches = text.match(/\/Type\s*\/Page[^s]/g);
  return matches?.length ?? 0;
};

describe("branded analytics schedule PDF", () => {
  it("renders a landscape PDF with logo, KPI cards, and table", async () => {
    const logo = getDefaultWorklenzLogoBuffer();
    expect(logo?.length).toBeGreaterThan(0);

    const pdf = await renderSchedulePdf({
      title: "Velocity",
      rows: [
        ["Sprint", "Committed", "Completed"],
        ["Sprint 1", "30", "28"],
        ["Sprint 2", "32", "30"],
      ],
      logo,
      kpis: [
        { label: "Avg velocity", value: "29", tone: "#1890ff" },
        { label: "Commitment", value: "93%", tone: "#faad14" },
      ],
      footerNote: "Auto-generated by Worklenz · test",
    });

    expect(isPdf(pdf)).toBe(true);
    expect(pdf.length).toBeGreaterThan(1000);
  });

  it("maps velocity chart source KPIs into PDF tiles", () => {
    const source = {
      kind: "velocity",
      data: {
        series: [],
        kpis: {
          avg_velocity: 12.5,
          last_sprint_velocity: 14,
          commitment_accuracy_pct: 90,
          completed_sprint_count: 4,
        },
        meta: {
          min_sprints_met: true,
          view_by: "sprint",
          metric: "points",
          avg_window: 5,
          bucket: "sprint",
        },
        last_updated_at: new Date().toISOString(),
      },
    } as ScheduleChartSource;

    const tiles = buildSchedulePdfKpis(source);
    expect(tiles).toHaveLength(4);
    expect(tiles[0].label).toBe("Avg velocity");
    expect(tiles[0].value).toBe("12.5");
  });

  it("writes a sample PDF artifact for visual review", async () => {
    const logo = getDefaultWorklenzLogoBuffer();
    const exportedOn = new Date().toISOString().slice(0, 10);
    const pdf = await renderSchedulePdf({
      title: "Project Health (sample)",
      rows: [
        ["Project", "Health", "Progress %", "Open", "Overdue"],
        ["Website Redesign", "On track", "72", "14", "2"],
        ["Mobile App", "At risk", "48", "31", "7"],
        ["API Platform", "Off track", "35", "22", "9"],
      ],
      logo,
      exportedOn,
      footerNote: `Auto-generated by Worklenz · ${exportedOn} · Project Health (sample)`,
      kpis: [
        { label: "On track", value: "12", sub: "projects", tone: "#52c41a" },
        { label: "At risk", value: "4", sub: "projects", tone: "#faad14" },
        { label: "Off track", value: "2", sub: "projects", tone: "#ff4d4f" },
        { label: "Overdue tasks", value: "18", sub: "across selection", tone: "#1890ff" },
      ],
    });

    const outDir = path.join(__dirname, "../../tmp");
    fs.mkdirSync(outDir, { recursive: true });
    const outPath = path.join(outDir, "sample-analytics-report.pdf");
    fs.writeFileSync(outPath, pdf);
    expect(fs.existsSync(outPath)).toBe(true);
    expect(isPdf(fs.readFileSync(outPath))).toBe(true);
  });

  it("renders Project Health with KPIs and side-by-side bar + donut on page 1", async () => {
    const logo = getDefaultWorklenzLogoBuffer();
    // Minimal 1x1 PNG — enough for react-pdf Image embedding.
    const tinyPng = Buffer.from(
      "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==",
      "base64"
    );

    const pdf = await renderSchedulePdf({
      title: "Project Health",
      rows: [
        ["Project", "Health", "Progress %", "Open", "Overdue"],
        ["Website Redesign", "On track", "72", "14", "2"],
        ["Mobile App", "At risk", "48", "31", "7"],
      ],
      logo,
      chartPngs: [tinyPng, tinyPng],
      chartTitles: ["Progress & budget", "Health status"],
      kpis: [
        { label: "On track", value: "12", sub: "projects", tone: "#52c41a" },
        { label: "At risk", value: "4", sub: "projects", tone: "#faad14" },
        { label: "Off track", value: "2", sub: "projects", tone: "#ff4d4f" },
        { label: "Overdue tasks", value: "18", sub: "across selection", tone: "#1890ff" },
      ],
      footerNote: "Auto-generated by Worklenz · test · Project Health",
    });

    expect(isPdf(pdf)).toBe(true);
    expect(pdf.length).toBeGreaterThan(1500);

    const outDir = path.join(__dirname, "../../tmp");
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(path.join(outDir, "sample-project-health-side-by-side.pdf"), pdf);
  });

  it("chunks table rows so each page can show its own column header", () => {
    expect(chunkRows([], 12)).toEqual([[]]);
    expect(chunkRows([1, 2, 3], 2)).toEqual([[1, 2], [3]]);
    expect(chunkRows(Array.from({ length: 25 }, (_, i) => i), TABLE_ROWS_PER_PAGE)).toHaveLength(
      3
    );
  });

  it("detects PVA numeric columns including variance days labels", () => {
    expect(isNumericCellValue("+3 days")).toBe(true);
    expect(isNumericCellValue("-1.5 days")).toBe(true);
    expect(isNumericCellValue("0 days")).toBe(true);
    expect(isNumericCellValue("42")).toBe(true);
    expect(isNumericCellValue("Website Redesign")).toBe(false);

    expect(
      detectNumericColumns(
        ["Project", "Planned tasks", "Completed", "Overdue", "Variance"],
        [
          ["Website Redesign", "30", "28", "2", "+3 days"],
          ["Mobile App", "12", "10", "0", "-1 days"],
        ]
      )
    ).toEqual([false, true, true, true, true]);
  });

  it("renders PVA tasks PDF with right-aligned numeric columns", async () => {
    const logo = getDefaultWorklenzLogoBuffer();
    const pdf = await renderSchedulePdf({
      title: "Planned vs Actual: Tasks",
      rows: [
        ["Project", "Planned tasks", "Completed", "Overdue", "Variance"],
        ["Website Redesign", "30", "28", "2", "+3 days"],
        ["Mobile App", "12", "10", "0", "-1.5 days"],
        ["API Platform", "8", "8", "0", "0 days"],
      ],
      logo,
      kpis: [
        { label: "Planned tasks", value: "50", tone: "#1890ff" },
        { label: "Avg variance", value: "0.5", tone: "#faad14" },
      ],
      footerNote: "Auto-generated by Worklenz · test · PVA tasks alignment",
    });

    expect(isPdf(pdf)).toBe(true);
    const outDir = path.join(__dirname, "../../tmp");
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(path.join(outDir, "sample-pva-tasks-right-align.pdf"), pdf);
  });

  it("renders a multi-page table PDF with a column header on every table page", async () => {
    const logo = getDefaultWorklenzLogoBuffer();
    const dataRows = Array.from({ length: TABLE_ROWS_PER_PAGE * 2 + 3 }, (_, i) => [
      `Project ${i + 1}`,
      i % 2 === 0 ? "On track" : "At risk",
      String(40 + (i % 50)),
      String(i + 1),
      String(i % 5),
    ]);

    const pdf = await renderSchedulePdf({
      title: "Project Health (multi-page table)",
      rows: [["Project", "Health", "Progress %", "Open", "Overdue"], ...dataRows],
      logo,
      kpis: [{ label: "Projects", value: String(dataRows.length), tone: "#1890ff" }],
      footerNote: "Auto-generated by Worklenz · test · multi-page table",
    });

    expect(isPdf(pdf)).toBe(true);
    // 1 summary page + 3 table pages (12 + 12 + 3 rows)
    expect(countPdfPages(pdf)).toBeGreaterThanOrEqual(4);

    const outDir = path.join(__dirname, "../../tmp");
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(path.join(outDir, "sample-schedule-multipage-table.pdf"), pdf);
  });
});
