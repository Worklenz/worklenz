for (const lang of TARGET_LANGS) {
  const filePath = path.join(LOCALES_DIR, lang, 'schedule.json');
  let locale = readJson(filePath);
  if (!locale) {
    console.error(`Skipping ${lang}: could not read file`);
    continue;
  }

  const trans = translations[lang] || {};
  let addedCount = 0;
  let updatedCount = 0;
  for (const [key, value] of Object.entries(source)) {
    if (!(key in locale)) {
      locale[key] = trans[key] || value;
      addedCount++;
    } else if (trans[key] && locale[key] === value) {
      locale[key] = trans[key];
      updatedCount++;
    }
  }

  // Also remove extra keys not in source
  const sourceKeys = Object.keys(source);
  let removedCount = 0;
  for (const key of Object.keys(locale)) {
    if (!sourceKeys.includes(key)) {
      delete locale[key];
      removedCount++;
    }
  }

  writeJson(filePath, locale);
  console.log(`  ${lang}: added ${addedCount} keys, updated ${updatedCount} translations, removed ${removedCount} extra keys`);
}

console.log('\nDone!');
